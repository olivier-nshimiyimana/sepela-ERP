import { DEFAULT_LOCALE, translate } from "../i18n";

/** Fixed platform vendor name on every invoice (not the merchant's company name). */
export const PLATFORM_COMPANY_NAME = "SEPELA INC";

/** @deprecated Use getPlatformCompanyLine(locale) for localized receipts. */
export const PLATFORM_COMPANY_LINE = `Generated by: ${PLATFORM_COMPANY_NAME}`;

export function getPlatformCompanyLine(locale = DEFAULT_LOCALE) {
  return translate("branding.generatedBy", locale, { company: PLATFORM_COMPANY_NAME });
}
